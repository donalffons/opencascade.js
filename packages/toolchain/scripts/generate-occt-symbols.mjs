#!/usr/bin/env node
/**
 * Emit `generated/occt-symbols.d.ts` — the `OcctSymbol` literal union covering
 * every name the container-side `bindings:` list accepts.
 */
import { loadSymbolUniverse, writeGenerated } from './lib/symbols.mjs';

const { provenance, entries } = loadSymbolUniverse();

const contents = `// GENERATED by packages/toolchain/scripts/generate-occt-symbols.mjs from ${provenance} — do not edit.

/**
 * Every symbol the container-side \`bindings:\` list accepts: OCCT classes and
 * enums from the release's api-reference, plus the OCCT \`typedef\` aliases the
 * bindgen resolves to canonical instantiations.
 *
 * Custom symbols provided by \`customBindings[].file\` are **not** here — they
 * are inferred from the config's own \`customBindings[].symbols\` declarations.
 */
export type OcctSymbol =
${entries.map((entry) => `  | '${entry.name}'`).join('\n')};
`;

writeGenerated('occt-symbols.d.ts', contents);
process.stdout.write(`  ${entries.length} symbols\n`);
