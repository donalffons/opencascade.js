/**
 * Render the eager root: capability-probed init plus a named-export barrel.
 *
 * @param symbols - The unioned symbol lists (same input as the d.ts).
 * @param assets - Per-variant glue and WASM asset metadata.
 * @returns The file contents.
 */
export const renderEagerRoot = (
  symbols: CollectedSymbols,
  assets: readonly VariantAsset[],
): string =>
  [
    GENERATED_BANNER('the shared symbol list'),
    '// Eager root: selects a variant, initialises it with top-level await, and',
    '// re-exports every bound symbol as a named value. Import `./init` instead to',
    '// control when (and whether) the WASM module is instantiated.',
    "import { createInstance, selectVariant } from './init.js';",
    '',
    `const IS_NODE = ${IS_NODE_SNIPPET};`,
    'const variant = selectVariant();',
    'const wasmUrl = (() => {',
    '  switch (variant) {',
    ...assets.map(
      (asset) =>
        `    case '${asset.name}':\n      return new URL('./${asset.outputName}.wasm', import.meta.url).href;`,
    ),
    '    default:',
    "      throw new Error(`Unknown selected variant \"${variant}\".`);",
    '  }',
    '})();',
    "const wasmPath = !IS_NODE || !wasmUrl.startsWith('file:')",
    '  ? wasmUrl',
    '  : (() => {',
    '      const filePath = decodeURIComponent(new URL(wasmUrl).pathname);',
    "      return process.platform === 'win32' ? filePath.replace(/^\\/([A-Za-z]:)/, '$1') : filePath;",
    '    })();',
    'const oc = await createInstance({',
    '  variant,',
    "  locateFile: (file, prefix = '') => (file.endsWith('.wasm') ? wasmPath : `${prefix}${file}`),",
    '});',
    '',
    'export default oc;',
    ...symbols.values.map((symbol) =>
      symbols.exclusive.has(symbol)
        ? `export const ${symbol} = oc.${symbol}; // variant-exclusive: ${(symbols.exclusive.get(symbol) ?? []).join(', ')}`
        : `export const ${symbol} = oc.${symbol};`,
    ),
    '',
  ].join('\n');

/**
 * Re-export the whole shared surface as types.
 *
 * `types.d.ts` exports every bound symbol as a runtime *value* (the eager root
 * really does bind them). The lazy entries do not, so they re-export the
 * same names with `export type *`: `import { TopoDS_Shape } from '<pkg>'` keeps
 * working in type position — the surface the per-variant `export type { X }`
 * d.ts files gave before assemble unified them — without promising a value the
 * lazy entries never export.
 */
const TYPE_ONLY_REEXPORT = "export type * from './types.js';";

const renderInitTypes = (): string =>
  `${GENERATED_BANNER('the shared symbol list')}import type { CreateInstanceOptions, OpenCascadeInstance } from './types.js';

${TYPE_ONLY_REEXPORT}

/** Pre-import variant override key: \`globalThis[SELECT_OVERRIDE] = 'multi'\`. */
export declare const SELECT_OVERRIDE: symbol;

/** Most capable variant this host supports. */
export declare const selectVariant: () => string;

/** Create a fully initialised instance. */
export declare const createInstance: (
  options?: CreateInstanceOptions,
) => Promise<OpenCascadeInstance>;

export default createInstance;
`;

const renderPinnedInitTypes = (asset: VariantAsset): string => {
  const options = asset.requires.includes('threads')
    ? `InitOpenCascadeOptions & {
  /** Size of OCCT's default thread pool. */
  threadCount?: number;
}`
    : 'InitOpenCascadeOptions';

  return `${GENERATED_BANNER('the shared symbol list')}import type { InitOpenCascadeOptions, OpenCascadeInstance } from './types.js';

${TYPE_ONLY_REEXPORT}

/** Options accepted by this fixed-variant initializer. */
export type CreateInstanceOptions = ${options};

/** Create a fully initialised "${asset.name}" instance. */
export declare const createInstance: (
  options?: CreateInstanceOptions,
) => Promise<OpenCascadeInstance>;

export default createInstance;
`;
};

const renderEagerRootTypes = (): string =>
  `${GENERATED_BANNER('the shared symbol list')}import type { OpenCascadeInstance } from './types.js';

export * from './types.js';

/** The instance this entry initialised at import time. */
declare const oc: OpenCascadeInstance;
export default oc;
`;

const renderVariantTypes = (): string =>
  `${GENERATED_BANNER('the shared symbol list')}import type { InitOpenCascadeOptions, OpenCascadeInstance } from './types.js';

// The per-variant subpaths resolve to the raw Emscripten glue, whose only
// export is the module factory. Named symbol exports live on the root entry.
${TYPE_ONLY_REEXPORT}

declare const init: (options?: InitOpenCascadeOptions) => Promise<OpenCascadeInstance>;
export default init;
`;

/**
 * Build the `exports` fragment.
 *
 * `./<variant>/init` is emitted only for a multi-variant package: with one
 * variant the shared `./init` already resolves exactly one glue, so a pinned
 * entry would duplicate it. Multi-variant pinned entries receive exact
 * declarations that omit the shared selector and `variant` option.
 *
 * @param assets - Per-variant packaging facts.
 * @param distName - Dist directory name relative to the package root.
 * @returns Subpath → target, with package-root-relative paths.
 */
export const renderExports = (
  assets: readonly VariantAsset[],
  distName: string,
): ExportsMap => {
  const target = (file: string): string => `./${path.posix.join(distName, file)}`;
  const map: ExportsMap = {
    '.': { types: target(ASSEMBLE_OUTPUTS.rootTypes), default: target(ASSEMBLE_OUTPUTS.root) },
    './init': { types: target(ASSEMBLE_OUTPUTS.initTypes), default: target(ASSEMBLE_OUTPUTS.init) },
  };
  for (const asset of assets) {
    map[`./${asset.name}`] = {
      types: target(ASSEMBLE_OUTPUTS.variantTypes),
      default: target(`${asset.outputName}.js`),
    };
    if (assets.length > 1) {
      map[`./${asset.name}/init`] = {
        types: target(variantInitTypesFile(asset.name)),
        default: target(variantInitFile(asset.name)),
      };
    }
    map[`./${asset.name}/wasm`] = target(`${asset.outputName}.wasm`);
  }
  return map;
};

/**
 * Merge a generated fragment into an existing `exports` map.
 *
 * Generated subpaths win; every other existing subpath is preserved in place,
 * which is what keeps hand-declared aliases (`./wasm`, `./api-reference.json`,
 * `./package.json`) working.
 *
 * @param existing - The package's current `exports` map.
 * @param fragment - The generated fragment.
 * @returns The merged map: existing keys in their original order, then new ones.
 */
export const mergePackageExports = (
  existing: ExportsMap | undefined,
  fragment: ExportsMap,
): ExportsMap => {
  const merged: ExportsMap = {};
  for (const [subpath, entry] of Object.entries(existing ?? {})) {
    merged[subpath] = fragment[subpath] ?? entry;
  }
  for (const [subpath, entry] of Object.entries(fragment)) {
    merged[subpath] ??= entry;
  }
  return merged;
};

/** Whether a package `files` entry belongs to `libcascade assemble`. */
const isGeneratedPackageFile = (file: string, distName: string): boolean => {
  const normalized = file.replace(/^\.\//, '');
  const directory = distName.replace(/^\.\//, '').replace(/\/$/, '');
  const prefix = directory === '.' ? '' : `${directory}/`;
  if (!normalized.startsWith(prefix)) return false;
  const name = normalized.slice(prefix.length);
  return (
    Object.values(ASSEMBLE_OUTPUTS).includes(name as (typeof ASSEMBLE_OUTPUTS)[keyof typeof ASSEMBLE_OUTPUTS]) ||
    /^init\..+\.js$/.test(name) ||
    /(?:\.js|\.wasm|\.d\.ts)$/.test(name)
  );
};

/** Replace generated dist entries while preserving every hand-maintained file. */
export const mergePackageFiles = (
  existing: readonly string[] | undefined,
  generated: readonly string[],
  distName: string,
): string[] => {
  const merged: string[] = [];
  let inserted = false;
  for (const file of existing ?? []) {
    if (isGeneratedPackageFile(file, distName)) {
      if (!inserted) {
        merged.push(...generated);
        inserted = true;
      }
    } else {
      merged.push(file);
    }
  }
  if (!inserted) merged.push(...generated);
  return [...new Set(merged)];
};

/** Package files produced or consumed by one assemble run. */
const renderPackageFiles = (
  assets: readonly VariantAsset[],
  distName: string,
): string[] => {
  const target = (file: string): string => path.posix.join(distName, file);
  const outputs = [
    ASSEMBLE_OUTPUTS.types,
    ASSEMBLE_OUTPUTS.init,
    ASSEMBLE_OUTPUTS.initTypes,
    ASSEMBLE_OUTPUTS.variantTypes,
    ASSEMBLE_OUTPUTS.root,
    ASSEMBLE_OUTPUTS.rootTypes,
    ...(assets.length > 1
      ? assets.flatMap((asset) => [variantInitFile(asset.name), variantInitTypesFile(asset.name)])
      : []),
  ];
  const artifacts = assets.flatMap((asset) => [
    `${asset.outputName}.js`,
    `${asset.outputName}.wasm`,
  ]);
  return [...outputs, ...artifacts].map(target);
};

/**
 * Generate the packaging surface for a built config.
 *
 * @param options - Config, package root, and optional dist/package-name overrides.
 * @returns The written paths, the exports fragment, and symbol statistics.
 * @throws Error when a variant's build artifacts are missing.
 * @example
 * ```typescript
 * const { exports } = assemble({ config, configDirectory: process.cwd() });
 * ```
 */
export const assemble = (options: AssembleOptions): AssembleResult => {
  const { config, configDirectory } = options;
  const distDirectory = options.distDirectory ?? path.join(configDirectory, 'dist');
  const packageJsonPath = path.join(configDirectory, 'package.json');
  const packageName =
    options.packageName ??
    (fs.existsSync(packageJsonPath)
      ? readJson<{ name?: string }>(packageJsonPath).name
      : undefined) ??
    config.name;

  const parsed = readVariantDts(config, distDirectory);
  const assets = readVariantAssets(config, distDirectory);
  const normalizedGlue = normalizeThreadedGlue(assets, distDirectory);
  const symbols = collectSymbols(parsed);
  const files: Record<string, string> = {
    [ASSEMBLE_OUTPUTS.types]: renderSharedTypes(
      parsed,
      symbols,
      config.variants.map((variant) => variant.name),
    ),
    [ASSEMBLE_OUTPUTS.init]: renderInit(assets, packageName),
    [ASSEMBLE_OUTPUTS.initTypes]: renderInitTypes(),
    [ASSEMBLE_OUTPUTS.variantTypes]: renderVariantTypes(),
    [ASSEMBLE_OUTPUTS.root]: renderEagerRoot(symbols, assets),
    [ASSEMBLE_OUTPUTS.rootTypes]: renderEagerRootTypes(),
  };

  // One glue-pinned entry per variant, for consumers that know which variant
  // they want. Skipped at N=1, where `./init` is already exactly this file.
  if (assets.length > 1) {
    for (const asset of assets) {
      files[variantInitFile(asset.name)] = renderPinnedInit(asset, packageName);
      files[variantInitTypesFile(asset.name)] = renderPinnedInitTypes(asset);
    }
  }

  const distName = path.relative(configDirectory, distDirectory) || '.';
  const exportsMap = renderExports(assets, distName);
  const packageFiles = renderPackageFiles(assets, distName);
  files[ASSEMBLE_OUTPUTS.exports] = `${JSON.stringify({ exports: exportsMap }, undefined, 2)}\n`;

  fs.mkdirSync(distDirectory, { recursive: true });
  const generated = Object.entries(files).map(([name, contents]) => {
    const filePath = path.join(distDirectory, name);
    fs.writeFileSync(filePath, contents);
    return filePath;
  });
  const written = [...normalizedGlue, ...generated];

  return {
    written,
    exports: exportsMap,
    files: packageFiles,
    sharedSymbolCount: symbols.values.length - symbols.exclusive.size,
    exclusiveSymbols: symbols.exclusive,
  };
};

/**
 * Merge generated exports and package files into the package's package.json.
 *
 * @param configDirectory - Package root holding package.json.
 * @param fragment - The fragment returned by {@link assemble}.
 * @param files - Generated `files` entries returned by {@link assemble}.
 * @returns The absolute path written.
 */
export const writePackageExports = (
  configDirectory: string,
  fragment: ExportsMap,
  files: readonly string[],
): string => {
  const packageJsonPath = path.join(configDirectory, 'package.json');
  const packageJson = readJson<{ exports?: ExportsMap; files?: string[] }>(packageJsonPath);
  const mergedExports = mergePackageExports(packageJson.exports, fragment);
  const firstTarget = files[0];
  const distName = firstTarget === undefined ? 'dist' : path.posix.dirname(firstTarget);
  const mergedFiles = mergePackageFiles(packageJson.files, files, distName);
  fs.writeFileSync(
    packageJsonPath,
    `${JSON.stringify({ ...packageJson, exports: mergedExports, files: mergedFiles }, undefined, 2)}\n`,
  );
  return packageJsonPath;
};
